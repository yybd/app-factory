#!/usr/bin/env python3
"""Apple's accepted media dimensions, read from the one file that states them.

    from apple_specs import screenshot_sizes, preview_sizes, render_markdown

These numbers lived in seven places in this track — two scripts, three reference
documents and two SKILL.md files — and they had already drifted: 1290×2796 was filed
under 6.7" in one table and 6.9" in another. Apple says 6.9". Nobody could have caught
it by reading, because each copy is internally consistent and looks right; the only way
to see a disagreement between seven tables is to have one table.

`apple-specs.json` beside this file is that table. It carries the URL it came from and
the date it was last checked, because these change — an iPhone generation adds a size
roughly every year, and the honest thing a file can do is say how old it is.

Both halves are here so neither can drift from the other: `screenshot_sizes()` for the
scripts that validate files, `render_markdown()` for the reference documents, which are
generated by `render_specs.py` rather than maintained by hand.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SPECS = os.path.join(HERE, "apple-specs.json")


def load():
    with open(SPECS, encoding="utf-8") as f:
        return json.load(f)


def screenshot_sizes(platforms=None):
    """{(w, h): "label"} for every accepted screenshot size, both orientations.

    Landscape is derived rather than listed: Apple accepts the transpose of every
    portrait size, and writing both out doubled the table for no information.
    """
    d = load()["screenshots"]
    out = {}
    for platform, families in d.items():
        if platforms and platform not in platforms:
            continue
        for fam in families:
            label = f"{platform} {fam['family']}".strip()
            for w, h in fam["sizes"]:
                out[(w, h)] = label
                if w != h:
                    out[(h, w)] = label + " landscape"
    return out


def preview_sizes():
    """{(w, h): "label"} for App Preview videos."""
    out = {}
    for platform, sizes in load()["previews"].items():
        for w, h in sizes:
            out[(w, h)] = f"{platform} preview"
    return out


def duo_sizes():
    """{(w, h): "label"} for the iPhone Duo stills, both orientations.

    Kept apart from the rest because they travel a different road: fastlane `deliver`
    has no Duo display type, so a Duo still handed to it fails the run. The deliver
    staging holds them back by this set; the Asset Library uploader sends them.
    """
    return screenshot_sizes(platforms=["iphone_duo"])


def creative_placements():
    """The creative-asset placements (product page header, search results), as stored."""
    return load().get("creative_assets", {}).get("placements", [])


def creative_matches(w, h, ext, video=False):
    """[label] of every creative placement a (w, h, ext) file is accepted by.

    Images are exact for the header and a RANGE for search results, so this is not a
    lookup in a size table the way screenshots are. An empty list means the file fits
    no placement — which is the answer a verifier needs, not an exception.
    """
    ext = ext.lower().lstrip(".")
    out = []
    for p in creative_placements():
        specs = [p["video"]] if video else p["images"]
        for s in specs:
            (wmin, hmin), (wmax, hmax) = s["min"], s["max"]
            if wmin <= w <= wmax and hmin <= h <= hmax and ext in s["formats"]:
                if _ratio_ok(w, h, s["ratio"]):
                    out.append(p["label"] + (" (universal 16:9)" if s.get("universal") else ""))
    return out


def creative_video_rules():
    """{label: (fps_list, (min_s, max_s))} — what a creative video must also satisfy."""
    return {p["label"]: (p["video"]["fps"], tuple(p["video"]["seconds"]))
            for p in creative_placements()}


def _ratio_ok(w, h, ratio):
    # Within 1%: Apple's 21:9 is 3840x1646 (2.333…), and a range spec has to be held to
    # its ratio or a portrait file inside the box would pass as a "search results" image.
    a, b = (int(x) for x in ratio.split(":"))
    return abs((w / h) - (a / b)) <= 0.01 * (a / b)


def cert_types():
    """[(prefix, what it is for)] — the certificate table both signing scripts read.

    It was written out in `apple_creds.py` and `diagnose_signing.py`, and the two had
    already worded three of the ten differently. Nothing depends on the wording, which
    is exactly why nobody would ever have reconciled them.
    """
    return [(c["prefix"], c["does"]) for c in load()["certificates"]["types"]]


def checked_on():
    d = load()
    return d.get("_checked", "?"), d.get("_source", "")


def render_markdown():
    """The reference tables, generated. What `render_specs.py` writes into the docs."""
    d = load()
    when, src = checked_on()
    L = [f"*Generated from `apple-specs.json`. Apple's source: {src}",
         f"Last checked against it: {when}. Do not edit this section by hand —",
         "edit the JSON and run `render_specs.py`.*", "",
         f"{d['_rules']}", ""]
    for platform, families in d["screenshots"].items():
        L.append(f"### {platform}")
        L.append("")
        L.append("| Family | Portrait sizes | Devices |")
        L.append("|---|---|---|")
        for fam in families:
            sizes = " · ".join(f"{w} × {h}" for w, h in fam["sizes"])
            L.append(f"| {fam['family']} | {sizes} | {fam['devices']} |")
        L.append("")
    L.append("**Landscape is the transpose of every size above**, and is accepted wherever")
    L.append("the portrait one is.")
    L.append("")
    L.append(d.get("_watch_note", ""))
    L.append("")
    if d.get("_duo_note"):
        L.append(d["_duo_note"])
        L.append("")
    L.append("### App Preview videos")
    L.append("")
    L.append("| Platform | Sizes |")
    L.append("|---|---|")
    for platform, sizes in d["previews"].items():
        L.append(f"| {platform} | " + " · ".join(f"{w} × {h}" for w, h in sizes) + " |")
    L.append("")
    L.append(d.get("_preview_rules", ""))
    if d.get("_preview_duo_note"):
        L.append("")
        L.append(d["_preview_duo_note"])
    ca = d.get("creative_assets")
    if ca:
        L.append("")
        L.append("### Creative assets — product page header and search results")
        L.append("")
        L.append(f"*Source: {ca['_source']} — checked {ca['_checked']}.*")
        L.append("")
        L.append("| Placement | Kind | Ratio | Size | Formats | Video |")
        L.append("|---|---|---|---|---|---|")
        for p in ca["placements"]:
            for s in p["images"] + [dict(p["video"], kind="video")]:
                kind = s.get("kind", "image")
                size = (f"{s['min'][0]} × {s['min'][1]}" if s["min"] == s["max"]
                        else f"{s['min'][0]} × {s['min'][1]} – {s['max'][0]} × {s['max'][1]}")
                vid = (f"{'/'.join(map(str, s['fps']))} fps, {s['seconds'][0]}–{s['seconds'][1]} s"
                       if kind == "video" else "")
                L.append(f"| {p['label']} | {kind} | {s['ratio']} | {size} | "
                         f"{', '.join(s['formats'])} | {vid} |")
        L.append("")
        L.append(ca["_rules"])
        L.append("")
        L.append(ca["_universal"])
    return "\n".join(L).rstrip() + "\n"


if __name__ == "__main__":
    when, src = checked_on()
    s, p = screenshot_sizes(), preview_sizes()
    print(f"apple-specs.json — checked {when}")
    print(f"  {len(s)} screenshot dimensions (both orientations), {len(p)} preview dimensions")
    print(f"  source: {src}")
